"""The process-wide cipher for stored responses, from ``MASTER_ENCRYPTION_KEYSET``.

Every service that encrypts or decrypts stored data with the keyset (the
backend, its jobs worker, the Google Forms integration) loads it here, once,
at startup, and is warned here when it holds a key published in the
repository (common.services.keyset).
"""

import os

from common.services.keyset import (
    KEYSET_ENV,
    CryptoService,
    UnreadableCiphertext,
    warn_if_published,
)

__all__ = [
    "CryptoService",
    "UnreadableCiphertext",
    "crypto_service",
    "default_crypto_service",
]


def _configured_keyset():
    """The keyset: the environment (an operator's override, also what a stack
    that predates the settings store has), else the settings store's verified
    row. A stack whose keys were generated by ``bootstrap-keys`` or pruned from
    the files after the import has it only in the store."""
    value = (os.environ.get(KEYSET_ENV) or "").strip()
    if value:
        return value
    from common.settings.loader import current_runtime

    runtime = current_runtime()
    resolved = runtime.resolve_key(KEYSET_ENV) if runtime is not None else None
    return (resolved.value or "").strip() if resolved is not None else ""


def default_crypto_service():
    encryption_keyset = _configured_keyset()
    if not encryption_keyset:
        raise Exception(
            "MASTER_ENCRYPTION_KEYSET is set neither in the environment nor in the settings store."
        )
    service = CryptoService(encryption_keyset)
    warn_if_published(encryption_keyset, KEYSET_ENV)
    return service


crypto_service = default_crypto_service()
