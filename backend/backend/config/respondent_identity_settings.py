from pydantic import Field
from pydantic_settings import SettingsConfigDict
from common.settings.loader.pydantic_source import StoreBackedSettings


class RespondentIdentitySettings(StoreBackedSettings):
    """The key of the respondent identity hash (RESPONDENT_IDENTITY_KEY).

    Hex or base64 text of at least 32 random bytes, generated by the operator
    (``openssl rand -hex 32``). It is not derived from the Fernet key or the
    keyset, and the API refuses to start without it
    (``backend.app.utils.respondent_identity.require_identity_key``). Never
    logged: ``repr=False`` keeps it out of a printed settings object.
    """

    KEY: str = Field("", repr=False)

    model_config = SettingsConfigDict(env_prefix="RESPONDENT_IDENTITY_")
