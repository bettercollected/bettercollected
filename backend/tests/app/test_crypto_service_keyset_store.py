"""The process-wide cipher finds the response keyset in the settings store when
the environment has none: a stack whose keys were generated by ``bootstrap-keys``
(or pruned from the env files after the import) holds the keyset only there, and
the services must start on it."""

from __future__ import annotations

import pytest

from common.services.crypto_service import default_crypto_service
from common.services.keyset import add_primary_key, encode_keyset
from tests.app.test_settings_keyset_fingerprint import KEYSET, _store
from tink.proto import tink_pb2


def test_a_store_only_keyset_builds_the_cipher(monkeypatch, tmp_path):
    monkeypatch.delenv(KEYSET, raising=False)
    _store(monkeypatch, tmp_path, encode_keyset(add_primary_key(tink_pb2.Keyset())))
    service = default_crypto_service()
    sealed = service.encrypt("w1", "f1", '{"q": "a"}')
    assert service.decrypt("w1", "f1", sealed) == b'{"q": "a"}'


def test_the_environment_keyset_wins_over_the_store(monkeypatch, tmp_path):
    env_keyset = add_primary_key(tink_pb2.Keyset())
    _store(monkeypatch, tmp_path, encode_keyset(add_primary_key(tink_pb2.Keyset())))
    monkeypatch.setenv(KEYSET, encode_keyset(env_keyset))
    service = default_crypto_service()
    # sealed by the environment's keyset: only that keyset opens it
    from common.services.keyset import CryptoService

    sealed = CryptoService(encode_keyset(env_keyset)).encrypt("w1", "f1", "x")
    assert service.decrypt("w1", "f1", sealed) == b"x"


def test_neither_source_refuses_to_start(monkeypatch):
    monkeypatch.delenv(KEYSET, raising=False)
    from common.settings.loader import runtime as runtime_module

    monkeypatch.setattr(runtime_module, "_runtime", None)
    with pytest.raises(Exception, match="neither in the environment nor in the settings store"):
        default_crypto_service()
